export function createT(lang: string): (key: string) => string {
  const dict = lang.toLowerCase().startsWith("zh") ? zhCN : enUS;
  return (key) => dict[key] ?? enUS[key] ?? key;
}

/** 键是否存在于字典（两字典键集由 i18n.test.ts 钉住一致，查 zhCN 即可）。
 *  用于动态 id 的 i18n 查找（如 agentMode.<id>）：无键时调用方回落原文，
 *  避免 createT 把键名本身当文案显示。 */
export function dictHas(key: string): boolean {
  return key in zhCN;
}
